#!/usr/bin/env bash
# Reproducibility proof (PLAN.md §11): generate the same scale twice with the same seed in separate JVM runs and
# compare checksums (expected IDENTICAL), then with a different seed (expected DIFFERENT fingerprint).
# Writes docs/evidence/reproducibility_report.md (override with REPORT=<file>). No database needed.
#
#   ./scripts/repro_check.sh [tiny|starter|full] [seed]
set -euo pipefail

SCALE="${1:-starter}"
SEED="${2:-20261022}"
OTHER_SEED=$((SEED + 1))
BASE="out/repro"
JAR="target/pricing-sim.jar"
REPORT="${REPORT:-docs/evidence/reproducibility_report.md}"
JAVA_OPTS="${JAVA_OPTS:--Xmx2g}"

cd "$(dirname "$0")/.."
[ -f "${JAR}" ] || ./mvnw -q -DskipTests package

gen() {
  # shellcheck disable=SC2086
  java ${JAVA_OPTS} -jar "${JAR}" generate --scale "${SCALE}" --seed "$1" --out "$2" > /dev/null
}
fingerprint() {
  sed -n 's/.*"dataset_fingerprint": "\([0-9a-f]*\)".*/\1/p' "$1/manifest.json"
}

rm -rf "${BASE}"
echo "Generating ${SCALE} (seed ${SEED}) into ${BASE}/run-a and ${BASE}/run-b, seed ${OTHER_SEED} into ${BASE}/run-c ..."
gen "${SEED}" "${BASE}/run-a"
gen "${SEED}" "${BASE}/run-b"
gen "${OTHER_SEED}" "${BASE}/run-c"

if diff "${BASE}/run-a/checksums.sha256" "${BASE}/run-b/checksums.sha256" > /dev/null; then
  VERDICT="IDENTICAL"
else
  VERDICT="DIFFERENT"
fi
FA=$(fingerprint "${BASE}/run-a"); FB=$(fingerprint "${BASE}/run-b"); FC=$(fingerprint "${BASE}/run-c")
if [ "${FC}" != "${FA}" ]; then SEED_VERDICT="DIFFERENT"; else SEED_VERDICT="IDENTICAL"; fi

rows() {  # rows of one file from a manifest
  sed -n "s|.*\"path\": \"$2\", \"rows\": \([0-9]*\),.*|\1|p" "$1/manifest.json"
}

mkdir -p "$(dirname "${REPORT}")"
{
  echo "# Reproducibility report"
  echo
  echo "Generated by \`scripts/repro_check.sh ${SCALE} ${SEED}\`: three separate \`generate\` runs (separate JVMs)."
  echo
  echo "| Item | Value |"
  echo "|---|---|"
  echo "| Scale | ${SCALE} |"
  echo "| Seed (run-a, run-b) | ${SEED} |"
  echo "| Seed (run-c) | ${OTHER_SEED} |"
  echo "| Java | $(java -version 2>&1 | head -1) |"
  echo "| OS | $(uname -sr) |"
  echo
  echo "## Same seed: run-a vs run-b"
  echo
  echo "| File | Rows a | Rows b | sha256 a | sha256 b | Match |"
  echo "|---|---|---|---|---|---|"
  while read -r SHA_A FILE; do
    SHA_B=$(awk -v f="${FILE}" '$2 == f {print $1}' "${BASE}/run-b/checksums.sha256")
    MATCH=$([ "${SHA_A}" = "${SHA_B}" ] && echo yes || echo "**no**")
    echo "| ${FILE} | $(rows "${BASE}/run-a" "${FILE}") | $(rows "${BASE}/run-b" "${FILE}") | \`${SHA_A:0:16}…\` | \`${SHA_B:0:16}…\` | ${MATCH} |"
  done < "${BASE}/run-a/checksums.sha256"
  echo
  echo "- Dataset fingerprint run-a: \`${FA}\`"
  echo "- Dataset fingerprint run-b: \`${FB}\`"
  echo "- \`diff run-a/checksums.sha256 run-b/checksums.sha256\`: $([ "${VERDICT}" = IDENTICAL ] && echo 'no differences' || echo 'differences found')"
  echo
  echo "**Verdict: ${VERDICT}**"
  echo
  echo "## Different seed: run-a vs run-c"
  echo
  echo "- Dataset fingerprint run-c (seed ${OTHER_SEED}): \`${FC}\`"
  echo
  echo "**Verdict: ${SEED_VERDICT}** (expected DIFFERENT: the seed drives every random stream)"
} > "${REPORT}"

echo "Same seed ${SEED}: ${VERDICT}"
echo "Different seed ${OTHER_SEED}: ${SEED_VERDICT}"
echo "Wrote ${REPORT}"
[ "${VERDICT}" = "IDENTICAL" ] && [ "${SEED_VERDICT}" = "DIFFERENT" ]
